/**
 * Trả về ngẫu nhiên các câu hỏi phân biệt âm dễ nhầm, xáo trộn đáp án mỗi lần chơi.
 */
export function getRandomConfusingChallenges(count = 10, pairType?: string): ConfusingSoundChallenge[] {
  let pool = [...confusingSoundChallenges];
  if (pairType && pairType !== 'all') {
    pool = pool.filter(c => c.pairType === pairType);
    if (pool.length === 0) pool = [...confusingSoundChallenges];
  }

  // Xáo trộn Fisher-Yates
  const shuffled = [...pool].sort(() => Math.random() - 0.5);
  const selected = shuffled.slice(0, Math.min(count, shuffled.length));

  // Xáo trộn thứ tự các đáp án trong từng câu
  return selected.map(q => ({
    ...q,
    distractors: [...q.distractors].sort(() => Math.random() - 0.5),
  }));
}
